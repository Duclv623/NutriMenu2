"""Export verified local NIN photos for current catalog and historical source IDs."""
import hashlib
import json
import re
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[3]
ROOT = REPO_ROOT / "BackendNutriMenu"
CATALOG = ROOT / "foodcatalogservice/src/main/resources/catalog"
STAGING = CATALOG / "nin-bulk-staging-20261125"
BULK = CATALOG / "nin-bulk-20261126"
DESTINATION = REPO_ROOT / "frontend/public/food-images/nin-bulk-20261126"
INDEX = REPO_ROOT / "frontend/src/data/ninImages.ts"


def load(path):
    return json.loads(path.read_text(encoding="utf-8-sig"))


def digest(data):
    return hashlib.sha256(data).hexdigest()


def verified_file(value, expected_hash):
    path = Path(value)
    path = (path if path.is_absolute() else STAGING / path).resolve()
    if not path.is_relative_to(STAGING.resolve()):
        raise ValueError(f"Photo escapes source staging: {value}")
    data = path.read_bytes()
    if digest(data) != expected_hash:
        raise ValueError(f"Photo hash mismatch: {path.name}")
    return path, data


def build():
    source = {r["_id"]: r for r in load(STAGING / "api-runs/bulk-20261125/dishes-source.json")}
    images = load(STAGING / "image-collection.json")["records"]
    crops = load(STAGING / "dish-photos/manifest.json")["records"]
    historical = load(CATALOG / "nin-real-20261123/nin-source-import.json")["dishes"]
    current = load(BULK / "nin-source-import.json")["dishes"]
    index, exports = {}, {}
    for row in historical + current:
        original = source[row["sourceRecordId"]]
        code = original["code"]
        if not re.fullmatch(r"[A-Za-z0-9_-]+", code):
            raise ValueError(f"Unsafe source code: {code}")
        evidence = images[code]
        if evidence.get("sourceRecordId") != row["sourceRecordId"] or evidence.get("imageUrl") != row["imageUrl"]:
            raise ValueError(f"Source identity/URL mismatch: {code}")
        photo_path, data = verified_file(evidence["localPath"], evidence["sha256"])
        kind = "ORIGINAL_SOURCE"
        crop = crops.get(code)
        if crop and crop.get("status") == "READY" and crop.get("originalImageSha256") == evidence["sha256"]:
            left, top, right, bottom = crop["cropBoxPixels"]
            valid_box = (0 <= left < right <= crop["originalWidth"]
                         and 0 <= top < bottom <= crop["originalHeight"]
                         and right - left == crop["croppedWidth"]
                         and bottom - top == crop["croppedHeight"])
            if valid_box:
                photo_path, data = verified_file(crop["croppedImagePath"], crop["croppedImageSha256"])
                kind = "CROPPED_SOURCE"
        filename = code + photo_path.suffix.lower()
        if filename in exports and exports[filename] != data:
            raise ValueError(f"Conflicting asset bytes: {filename}")
        exports[filename] = data
        index[row["code"]] = {"originalApiImageUrl": row["imageUrl"],
            "localAssetPath": f"/food-images/nin-bulk-20261126/{filename}",
            "sha256": digest(data), "originalImageSha256": evidence["sha256"], "kind": kind}

    # Resolve and verify all inputs before publishing any output.
    DESTINATION.mkdir(parents=True, exist_ok=True)
    for filename, data in exports.items():
        target = DESTINATION / filename
        target.write_bytes(data)
        if digest(target.read_bytes()) != digest(data):
            raise ValueError(f"Export verification failed: {filename}")
    INDEX.write_text(
        "// Generated by build_nin_bulk_frontend_assets.py; source identity and hashes verified.\n"
        "export type NinImage = {\n"
        "  readonly originalApiImageUrl: string;\n  readonly localAssetPath: string;\n"
        "  readonly sha256: string;\n  readonly originalImageSha256?: string;\n"
        '  readonly kind?: "CROPPED_SOURCE" | "ORIGINAL_SOURCE";\n};\n'
        "export const ninImages: Readonly<Record<string, NinImage>> = "
        + json.dumps(index, ensure_ascii=False, indent=2) + ";\n", encoding="utf-8")
    report = {"currentCatalogPhotos": len(current), "historicalIdentityPhotos": len(historical),
              "uniqueLocalAssets": len(exports), "indexedRuntimeIdentities": len(index),
              "currentCroppedPhotos": sum(index[r["code"]]["kind"] == "CROPPED_SOURCE" for r in current),
              "currentOriginalFallbacks": sum(index[r["code"]]["kind"] == "ORIGINAL_SOURCE" for r in current)}
    (BULK / "frontend-asset-report.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    print(json.dumps(report))


if __name__ == "__main__":
    build()
