"""Export only selected NIN source photos, preserving and verifying original bytes."""
import hashlib
import json
import re
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[3]
ROOT = REPO_ROOT / "BackendNutriMenu"
SOURCE = ROOT / "foodcatalogservice/src/main/resources/catalog/nin-real-20261123"
DESTINATION = REPO_ROOT / "frontend/public/food-images/nin-real-20261123"
INDEX = REPO_ROOT / "frontend/src/data/ninImages.ts"


def load(path):
    return json.loads(path.read_text(encoding="utf-8"))


def build():
    selected = load(SOURCE / "nin-source-import.json")["dishes"]
    recipes = load(SOURCE / "extracted-recipes.json")["recipes"]
    by_code = {row["code"]: row for row in recipes}
    if len(by_code) != len(recipes):
        raise ValueError("Duplicate extracted recipe code")
    if len(selected) != 40 or len({row["code"] for row in selected}) != 40:
        raise ValueError("Expected exactly 40 unique selected runtime codes")
    exports = []
    for row in sorted(selected, key=lambda item: item["code"]):
        if not re.fullmatch(r"NIN_REAL_VPF_\d{6}", row["code"]):
            raise ValueError(f"Invalid runtime code: {row['code']}")
        source_code = row["code"].removeprefix("NIN_REAL_").replace("_", "-")
        recipe = by_code[source_code]
        image = recipe["image"]
        relative = Path(image["local_path"])
        image_path = (SOURCE / relative).resolve()
        image_root = (SOURCE / "images").resolve()
        if relative.is_absolute() or not image_path.is_relative_to(image_root):
            raise ValueError(f"Image path escapes source image folder: {relative}")
        if image_path.name != f"{source_code}.webp":
            raise ValueError(f"Unexpected source image filename: {relative}")
        if row["imageUrl"] != image["source_url"] or row["sourceRecordId"] != recipe["source_id"]:
            raise ValueError(f"Runtime/source identity mismatch: {source_code}")
        expected_hash = image["sha256"]
        if not re.fullmatch(r"[0-9a-f]{64}", expected_hash):
            raise ValueError(f"Invalid original image hash: {source_code}")
        original = image_path.read_bytes()
        if hashlib.sha256(original).hexdigest() != expected_hash:
            raise ValueError(f"Original image hash mismatch: {source_code}")
        quality = json.loads(row["qualityJson"])
        if quality["imageSha256"] != expected_hash:
            raise ValueError(f"Runtime image hash mismatch: {source_code}")
        exports.append((row["code"], image_path.name, row["imageUrl"], expected_hash, original))

    # Validate every input before writing any generated output.
    DESTINATION.mkdir(parents=True, exist_ok=True)
    expected_names = {item[1] for item in exports}
    unexpected = {path.name for path in DESTINATION.iterdir()} - expected_names
    if unexpected:
        raise ValueError(f"Unexpected files in selected photo destination: {sorted(unexpected)}")
    index = {}
    for code, name, url, digest, original in exports:
        target = DESTINATION / name
        target.write_bytes(original)
        if hashlib.sha256(target.read_bytes()).hexdigest() != digest:
            raise ValueError(f"Exported image hash mismatch: {code}")
        index[code] = {
            "originalApiImageUrl": url,
            "localAssetPath": f"/food-images/nin-real-20261123/{name}",
            "sha256": digest,
        }
    INDEX.parent.mkdir(parents=True, exist_ok=True)
    entries = "\n".join(
        f"  {code}: {{\n"
        f"    originalApiImageUrl:\n      {json.dumps(image['originalApiImageUrl'])},\n"
        f"    localAssetPath: {json.dumps(image['localAssetPath'])},\n"
        f"    sha256: {json.dumps(image['sha256'])},\n"
        "  },"
        for code, image in index.items()
    )
    INDEX.write_text(
        "// Generated by foodcatalogservice/scripts/build_nin_frontend_assets.py.\n"
        "// Original downloaded source bytes; do not edit this index manually.\n"
        "export type NinImage = {\n"
        "  readonly originalApiImageUrl: string;\n"
        "  readonly localAssetPath: string;\n"
        "  readonly sha256: string;\n"
        "};\n"
        "export const ninImages: Readonly<Record<string, NinImage>> = {\n"
        + entries + "\n};\n",
        encoding="utf-8",
        newline="\n",
    )
    print(json.dumps({"selectedPhotos": len(exports), "originalAndExportedHashesVerified": len(exports)}))


if __name__ == "__main__":
    build()
